function buildDefaultComposition(type: GodUIComponentType, layers: LayerDefinition[]) {
  return {
    baseComponent: type as GodUIComponentType,
    layers: layers.map(l => ({ layerId: l.id, effects: [] })),
    tokens: [],
    tags: [],
  };
}

